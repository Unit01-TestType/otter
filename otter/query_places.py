def _normalize_place_types(
    place_types: Iterable[str],
) -> tuple[str, ...]:

    normalized = []

    for place_type in place_types:

        place_type = (
            str(place_type)
            .strip()
            .lower()
        )

        if place_type not in VALID_PLACE_TYPES:

            raise ValueError(
                f"Invalid place type '{place_type}'. "
                f"Valid values are: "
                f"{', '.join(sorted(VALID_PLACE_TYPES))}"
            )

        if place_type not in normalized:

            normalized.append(
                place_type
            )

    if not normalized:

        raise ValueError(
            "At least one place type must be selected."
        )

    return tuple(
        normalized
    )


def _normalize_admin_levels(
    admin_levels: Iterable[int],
) -> tuple[int, ...]:

    levels = sorted(
        {
            int(level)
            for level in admin_levels
        }
    )

    for level in levels:

        if not 1 <= level <= 15:

            raise ValueError(
                "Administrative levels must be "
                "between 1 and 15."
            )

    return tuple(levels)


def _normalize_name_languages(
    name_languages,
) -> Optional[tuple[str, ...]]:
    """
    Normalize requested OSM language codes.

    Returns None when the caller requested the local/default name.

    A single string is treated as one language rather than as an
    iterable of individual characters.
    """

    if name_languages is None:
        return None

    if isinstance(
        name_languages,
        str,
    ):

        name_languages = (
            name_languages,
        )

    normalized = []

    for language in name_languages:

        language = (
            str(language)
            .strip()
            .lower()
        )

        if not language:
            continue

        # OSM language keys normally consist of language codes and may
        # contain a region/script component such as pt-br or zh-hans.
        if not re.fullmatch(
            r"[a-z0-9]+(?:[-_][a-z0-9]+)*",
            language,
        ):

            raise ValueError(
                f"Invalid language code '{language}'."
            )

        if language not in normalized:

            normalized.append(
                language
            )

    if not normalized:

        raise ValueError(
            "name_languages must contain at least "
            "one language code."
        )

    return tuple(
        normalized
    )


