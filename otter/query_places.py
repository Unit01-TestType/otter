def query_places(
    bbox: Iterable[float],
    *,
    place_types: Iterable[str] = DEFAULT_PLACE_TYPES,
    name_languages=None,
    include_admin: bool = False,
    query: Optional[str] = None,
    admin_levels: Iterable[int] = DEFAULT_ADMIN_LEVELS,
    output: Optional[str | Path] = None,
    user_agent: str = (
        "MyOverpassPlaceTool/1.0 "
        "(replace-with-your-contact-information)"
    ),
    servers: Iterable[str] = DEFAULT_SERVERS,
    timeout: int = DEFAULT_TIMEOUT,
    request_delay: float = DEFAULT_REQUEST_DELAY,
    retries_per_server: int = DEFAULT_RETRIES_PER_SERVER,
    cache_path: Optional[str | Path] = DEFAULT_CACHE_PATH,
    max_results_per_tile: int = DEFAULT_MAX_RESULTS_PER_TILE,
    max_depth: int = DEFAULT_MAX_DEPTH,
    log_level: int = logging.WARNING,
) -> pd.DataFrame:
    """
    Query cities, towns, villages, and/or hamlets from OpenStreetMap.

    Parameters
    ----------
    **bbox**: *iterable*;
        Bounding box in the form:

            (south, west, north, east)

    **place_types**: *iterable, str*;
        One or more of:

            city
            town
            village
            hamlet

        Default:

            ("city", "town")

    **name_languages**: *iterable, str*
        Optional language or languages for place names.

        None:
            Use the local/default OSM "name" tag.

        "en":
            Use the English "name:en" tag as the primary name.

        ("en", "fr", "de"):
            Create name_en, name_fr, and name_de columns.
            The primary "name" column uses the first requested
            language available for each individual place.

        If none of the requested languages are available for a place,
        the local/default "name" tag is used.

        If a requested language is completely absent from the
        returned dataset, a warning is issued.

    **include_admin**: *bool*;
        Include administrative division names.

        Administrative boundary geometry is not downloaded.

    **query**: *str*;
        Optional custom Overpass QL query.

        Must contain:

            {bbox}

    **admin_levels**: *iterable, str*;
        Administrative levels to retrieve when include_admin=True.

    **output**: *str*;
        Optional output filename. Format is inferred from its extension.

    **user_agent**: *str*;
        Application-specific HTTP User-Agent.

    **servers**: *iterable, str*
        Overpass API endpoints.

    **timeout**: *int*;
        HTTP timeout in seconds.

    **request_delay**: *float*;
        Minimum delay between requests.

    **retries_per_server**: *int*;
        Number of retry attempts for transient failures.

    **cache_path**: *str*;
        SQLite cache path. Set to None to disable caching.

    **max_results_per_tile**: *int*;
        Maximum places allowed in a tile before subdivision.

    **max_depth**: *int*;
        Maximum recursive subdivision depth.

    **log_level**: *int*;
        Python logging level.

    Returns
    -------
    pandas.DataFrame
        Point-based place data.
    """

    logging.basicConfig(
        level=log_level,
        format=(
            "%(asctime)s "
            "%(levelname)s "
            "%(name)s: "
            "%(message)s"
        ),
    )

    normalized_bbox = BBox.from_tuple(
        bbox
    )

    normalized_place_types = (
        _normalize_place_types(
            place_types
        )
    )

    normalized_name_languages = (
        _normalize_name_languages(
            name_languages
        )
    )

    normalized_admin_levels = (
        _normalize_admin_levels(
            admin_levels
        )
    )

    if include_admin and not normalized_admin_levels:

        raise ValueError(
            "admin_levels cannot be empty when "
            "include_admin=True."
        )

    if timeout <= 0:

        raise ValueError(
            "timeout must be greater than zero."
        )

    if max_results_per_tile <= 0:

        raise ValueError(
            "max_results_per_tile must be greater than zero."
        )

    if max_depth < 0:

        raise ValueError(
            "max_depth cannot be negative."
        )

    if query is None:

        def query_builder(
            current_bbox: BBox,
        ) -> str:

            return _build_default_query(
                bbox=current_bbox,
                place_types=normalized_place_types,
                include_admin=include_admin,
                admin_levels=normalized_admin_levels,
                timeout=timeout,
            )

    else:

        if "{bbox}" not in query:

            raise ValueError(
                "Custom query must contain '{bbox}'."
            )

        def query_builder(
            current_bbox: BBox,
        ) -> str:

            return _build_custom_query(
                query,
                bbox=current_bbox,
                include_admin=include_admin,
                admin_levels=normalized_admin_levels,
                timeout=timeout,
            )

    cache = QueryCache(
        cache_path
    )

    try:

        client = OverpassClient(
            servers=servers,
            user_agent=user_agent,
            timeout=timeout,
            request_delay=request_delay,
            retries_per_server=retries_per_server,
            cache=cache,
        )

        places = _query_tile(
            client=client,
            bbox=normalized_bbox,
            query_builder=query_builder,
            include_admin=include_admin,
            admin_levels=normalized_admin_levels,
            name_languages=normalized_name_languages,
            max_results_per_tile=max_results_per_tile,
            max_depth=max_depth,
            depth=0,
        )

        places = _deduplicate_places(
            places
        )

        # Warn about languages only after the complete result set has
        # been assembled. This is important for large-area queries
        # because different recursive tiles may contain different
        # language coverage.
        _warn_about_missing_languages(
            places,
            normalized_name_languages,
        )

        if places:

            dataframe = pd.DataFrame(
                places
            )

            sort_columns = [
                column
                for column in (
                    "name",
                    "place",
                    "osm_id",
                )
                if column in dataframe.columns
            ]

            if sort_columns:

                dataframe.sort_values(
                    by=sort_columns,
                    kind="stable",
                    inplace=True,
                )

            dataframe.reset_index(
                drop=True,
                inplace=True,
            )

        else:

            columns = [
                "osm_id",
                "osm_type",
                "name",
            ]

            if normalized_name_languages is not None:

                columns.extend(
                    [
                        f"name_{language.replace('-', '_')}"
                        for language
                        in normalized_name_languages
                    ]
                )

            columns.extend(
                [
                    "place",
                    "population",
                    "latitude",
                    "longitude",
                    "wikidata",
                    "wikipedia",
                    "tags",
                ]
            )

            if include_admin:

                columns.append(
                    "country"
                )

                columns.extend(
                    [
                        f"admin_level_{level}"
                        for level
                        in normalized_admin_levels
                    ]
                )

                columns.append(
                    "administrative_divisions"
                )

            dataframe = pd.DataFrame(
                columns=columns
            )

        if output is not None:

            _write_output(
                dataframe,
                output,
            )

        return dataframe

    finally:

        cache.close()


