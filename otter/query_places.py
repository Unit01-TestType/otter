def _output_type(
    output: str | Path,
) -> str:

    suffix = (
        Path(output)
        .suffix
        .lower()
    )

    if suffix in (
        ".geojson",
        ".json",
    ):
        return "geojson"

    if suffix in (
        ".xlsx",
        ".xls",
    ):
        return "excel"

    if suffix == ".csv":
        return "csv"

    if suffix == ".shp":
        return "shapefile"

    raise ValueError(
        f"Unsupported output extension '{suffix}'. "
        "Supported extensions are: "
        ".geojson, .json, .xlsx, .xls, .csv, .shp"
    )


def _write_point_geospatial_output(
    dataframe: pd.DataFrame,
    output: str | Path,
    output_type: str,
) -> None:

    try:

        import geopandas as gpd

        from shapely.geometry import Point

    except ImportError as exc:

        raise ImportError(
            "GeoJSON/Shapefile output requires "
            "geopandas and shapely."
        ) from exc

    output_path = (
        Path(output)
        .expanduser()
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    geometry = [
        Point(
            longitude,
            latitude,
        )
        for longitude, latitude
        in zip(
            dataframe["longitude"],
            dataframe["latitude"],
        )
    ]

    gdf = gpd.GeoDataFrame(
        dataframe.copy(),
        geometry=geometry,
        crs="EPSG:4326",
    )

    if output_type == "geojson":

        gdf.to_file(
            output_path,
            driver="GeoJSON",
            encoding="utf-8",
        )

        return

    if output_type == "shapefile":

        shapefile_df = gdf.copy()

        if (
            "administrative_divisions"
            in shapefile_df.columns
        ):

            shapefile_df[
                "admin_divisions"
            ] = shapefile_df[
                "administrative_divisions"
            ].map(
                lambda value: (
                    json.dumps(
                        value,
                        ensure_ascii=False,
                    )
                    if isinstance(
                        value,
                        dict,
                    )
                    else value
                )
            )

            shapefile_df.drop(
                columns=[
                    "administrative_divisions"
                ],
                inplace=True,
            )

        if "tags" in shapefile_df.columns:

            shapefile_df["osm_tags"] = (
                shapefile_df["tags"].map(
                    lambda value: (
                        json.dumps(
                            value,
                            ensure_ascii=False,
                        )
                        if isinstance(
                            value,
                            dict,
                        )
                        else value
                    )
                )
            )

            shapefile_df.drop(
                columns=[
                    "tags"
                ],
                inplace=True,
            )

        shapefile_df.to_file(
            output_path,
            driver="ESRI Shapefile",
            encoding="utf-8",
        )

        return

    raise ValueError(
        f"Unsupported geospatial output type: "
        f"{output_type}"
    )


def _write_tabular_output(
    dataframe: pd.DataFrame,
    output: str | Path,
    output_type: str,
) -> None:

    output_path = (
        Path(output)
        .expanduser()
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    df = dataframe.copy()

    for column in df.columns:

        if df[column].map(
            lambda value: isinstance(
                value,
                (
                    dict,
                    list,
                    tuple,
                ),
            )
        ).any():

            df[column] = (
                df[column].map(
                    lambda value: (
                        json.dumps(
                            value,
                            ensure_ascii=False,
                        )
                        if isinstance(
                            value,
                            (
                                dict,
                                list,
                                tuple,
                            ),
                        )
                        else value
                    )
                )
            )

    if output_type == "csv":

        df.to_csv(
            output_path,
            index=False,
        )

        return

    if output_type == "excel":

        df.to_excel(
            output_path,
            index=False,
        )

        return

    raise ValueError(
        f"Unsupported tabular output type: "
        f"{output_type}"
    )


def _write_output(
    dataframe: pd.DataFrame,
    output: str | Path,
) -> None:

    output_type = _output_type(
        output
    )

    if output_type in (
        "geojson",
        "shapefile",
    ):

        _write_point_geospatial_output(
            dataframe,
            output,
            output_type,
        )

    else:

        _write_tabular_output(
            dataframe,
            output,
            output_type,
        )


