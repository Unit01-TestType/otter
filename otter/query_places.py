# Bounding box
# ============================================================================

@dataclass(frozen=True)
class BBox:
    """
    Geographic bounding box.

    Coordinate order:

        south, west, north, east
    """

    south: float
    west: float
    north: float
    east: float

    def __post_init__(self):

        if not -90.0 <= self.south <= 90.0:
            raise ValueError(
                "south must be between -90 and 90."
            )

        if not -90.0 <= self.north <= 90.0:
            raise ValueError(
                "north must be between -90 and 90."
            )

        if not -180.0 <= self.west <= 180.0:
            raise ValueError(
                "west must be between -180 and 180."
            )

        if not -180.0 <= self.east <= 180.0:
            raise ValueError(
                "east must be between -180 and 180."
            )

        if self.south >= self.north:
            raise ValueError(
                "south must be less than north."
            )

        if self.west >= self.east:
            raise ValueError(
                "west must be less than east."
            )

    @classmethod
    def from_tuple(
        cls,
        bbox: Iterable[float],
    ) -> "BBox":

        values = tuple(bbox)

        if len(values) != 4:
            raise ValueError(
                "bbox must contain exactly four values in the form "
                "(south, west, north, east)."
            )

        return cls(
            south=float(values[0]),
            west=float(values[1]),
            north=float(values[2]),
            east=float(values[3]),
        )

    def as_overpass(self) -> str:

        return (
            f"{self.south:.7f},"
            f"{self.west:.7f},"
            f"{self.north:.7f},"
            f"{self.east:.7f}"
        )

    def split(
        self,
    ) -> tuple["BBox", "BBox", "BBox", "BBox"]:

        mid_lat = (
            self.south + self.north
        ) / 2.0

        mid_lon = (
            self.west + self.east
        ) / 2.0

        return (
            BBox(
                self.south,
                self.west,
                mid_lat,
                mid_lon,
            ),
            BBox(
                self.south,
                mid_lon,
                mid_lat,
                self.east,
            ),
            BBox(
                mid_lat,
                self.west,
                self.north,
                mid_lon,
            ),
            BBox(
                mid_lat,
                mid_lon,
                self.north,
                self.east,
            ),
        )


