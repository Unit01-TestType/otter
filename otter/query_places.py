class QueryCache:
    """
    Small SQLite cache for complete Overpass responses.
    """

    def __init__(
        self,
        path: Optional[str | Path],
    ):

        self.enabled = path is not None

        if not self.enabled:

            self.connection = None
            return

        self.path = (
            Path(path)
            .expanduser()
        )

        self.path.parent.mkdir(
            parents=True,
            exist_ok=True,
        )

        self.connection = sqlite3.connect(
            str(self.path),
            timeout=30,
        )

        self.connection.execute(
            """
            CREATE TABLE IF NOT EXISTS overpass_cache (
                cache_key TEXT PRIMARY KEY,
                created_at REAL NOT NULL,
                response TEXT NOT NULL
            )
            """
        )

        self.connection.commit()

    def get(
        self,
        key: str,
    ) -> Optional[dict]:

        if not self.enabled:
            return None

        row = self.connection.execute(
            """
            SELECT response
            FROM overpass_cache
            WHERE cache_key = ?
            """,
            (key,),
        ).fetchone()

        if row is None:
            return None

        try:

            return json.loads(
                row[0]
            )

        except json.JSONDecodeError:

            logger.warning(
                "Ignoring invalid JSON in Overpass cache."
            )

            return None

    def put(
        self,
        key: str,
        response: dict,
    ) -> None:

        if not self.enabled:
            return

        self.connection.execute(
            """
            INSERT OR REPLACE INTO overpass_cache
            (
                cache_key,
                created_at,
                response
            )
            VALUES (?, ?, ?)
            """,
            (
                key,
                time.time(),
                json.dumps(response),
            ),
        )

        self.connection.commit()

    def close(self) -> None:

        if self.connection is not None:
            self.connection.close()


