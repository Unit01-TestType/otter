# Overpass HTTP client
# ============================================================================

class OverpassClient:

    def __init__(
        self,
        *,
        servers: Iterable[str],
        user_agent: str,
        timeout: int,
        request_delay: float,
        retries_per_server: int,
        cache: QueryCache,
    ):

        self.servers = tuple(
            server.rstrip("/")
            for server in servers
        )

        if not self.servers:

            raise ValueError(
                "At least one Overpass server is required."
            )

        self.user_agent = user_agent
        self.timeout = timeout

        self.request_delay = max(
            0.0,
            float(request_delay),
        )

        self.retries_per_server = max(
            1,
            int(retries_per_server),
        )

        self.cache = cache

        self.session = requests.Session()

        self.session.headers.update(
            {
                "User-Agent": user_agent,
                "Accept": "application/json",
                "Accept-Encoding": "gzip, deflate",
            }
        )

        self._last_request_time = 0.0

    @staticmethod
    def _cache_key(
        query: str,
        server: str,
    ) -> str:

        value = (
            server
            + "\n"
            + query
        )

        return hashlib.sha256(
            value.encode("utf-8")
        ).hexdigest()

    def _wait_for_rate_limit(self) -> None:

        elapsed = (
            time.monotonic()
            - self._last_request_time
        )

        remaining = (
            self.request_delay
            - elapsed
        )

        if remaining > 0:

            time.sleep(
                remaining
            )

    def execute(
        self,
        query: str,
    ) -> dict:

        last_error = None

        for server in self.servers:

            cache_key = (
                self._cache_key(
                    query,
                    server,
                )
            )

            cached = self.cache.get(
                cache_key
            )

            if cached is not None:

                logger.debug(
                    "Overpass cache hit."
                )

                return cached

            for attempt in range(
                1,
                self.retries_per_server + 1,
            ):

                try:

                    self._wait_for_rate_limit()

                    logger.debug(
                        "Overpass request to %s "
                        "(attempt %d/%d).",
                        server,
                        attempt,
                        self.retries_per_server,
                    )

                    self._last_request_time = (
                        time.monotonic()
                    )

                    response = self.session.post(
                        server,
                        data={
                            "data": query
                        },
                        timeout=self.timeout,
                    )

                    status = (
                        response.status_code
                    )

                    if status == 200:

                        try:

                            result = (
                                response.json()
                            )

                        except ValueError as exc:

                            raise OverpassError(
                                "Overpass returned HTTP 200 "
                                "but the response was not valid JSON."
                            ) from exc

                        self.cache.put(
                            cache_key,
                            result,
                        )

                        return result

                    if status in (
                        406,
                        429,
                    ):

                        last_error = (
                            OverpassHTTPError(
                                status,
                                (
                                    f"Overpass returned HTTP "
                                    f"{status} from {server}."
                                ),
                                response.text[:4000],
                            )
                        )

                        logger.warning(
                            "Overpass returned HTTP %d. "
                            "Waiting %.0f seconds.",
                            status,
                            OVERPASS_THROTTLE_DELAY,
                        )

                        time.sleep(
                            OVERPASS_THROTTLE_DELAY
                        )

                        continue

                    if status in (
                        500,
                        502,
                        503,
                        504,
                    ):

                        last_error = (
                            OverpassTemporaryError(
                                f"Temporary Overpass HTTP "
                                f"{status} error."
                            )
                        )

                        delay = min(
                            30.0,
                            2.0 ** attempt,
                        )

                        delay += random.uniform(
                            0.0,
                            1.0,
                        )

                        logger.warning(
                            "Overpass HTTP %d; "
                            "retrying in %.1f seconds.",
                            status,
                            delay,
                        )

                        time.sleep(
                            delay
                        )

                        continue

                    raise OverpassHTTPError(
                        status,
                        (
                            f"Overpass returned HTTP "
                            f"{status} from {server}."
                        ),
                        response.text[:4000],
                    )

                except requests.Timeout:

                    last_error = (
                        OverpassTemporaryError(
                            f"Timeout contacting {server}."
                        )
                    )

                    delay = min(
                        30.0,
                        2.0 ** attempt,
                    )

                    time.sleep(
                        delay
                    )

                except requests.ConnectionError as exc:

                    last_error = (
                        OverpassTemporaryError(
                            f"Connection error contacting "
                            f"{server}: {exc}"
                        )
                    )

                    delay = min(
                        30.0,
                        2.0 ** attempt,
                    )

                    time.sleep(
                        delay
                    )

                except OverpassHTTPError:

                    raise

        if last_error is not None:

            raise last_error

        raise OverpassError(
            "Overpass request failed."
        )


